// Generate the shell's self-hosted Claude fonts as a TS module of @font-face
// rules with base64 data-URI sources, so the injected shell chrome needs no
// Google Fonts CDN and works over both the loopback and dsh:// transports.
// Reads the woff2 files from the @fontsource devDependencies and writes
// src/main/shell-fonts.css.ts. Re-run after bumping a @fontsource package.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = dirname(fileURLToPath(new URL('../package.json', import.meta.url)))
const fontsDir = join(packageRoot, 'node_modules', '@fontsource')

/** The font faces the shell needs, keyed by @fontsource package. */
const FACES = {
  newsreader: [
    ['Newsreader', 400, 'normal', 'newsreader-latin-400-normal.woff2'],
    ['Newsreader', 400, 'italic', 'newsreader-latin-400-italic.woff2'],
    ['Newsreader', 500, 'normal', 'newsreader-latin-500-normal.woff2'],
  ],
  poppins: [
    ['Poppins', 400, 'normal', 'poppins-latin-400-normal.woff2'],
    ['Poppins', 500, 'normal', 'poppins-latin-500-normal.woff2'],
    ['Poppins', 600, 'normal', 'poppins-latin-600-normal.woff2'],
  ],
  lora: [
    ['Lora', 400, 'normal', 'lora-latin-400-normal.woff2'],
  ],
  'geist-mono': [
    ['Geist Mono', 400, 'normal', 'geist-mono-latin-400-normal.woff2'],
  ],
}

const rules = []
for (const [pkg, faces] of Object.entries(FACES)) {
  for (const [family, weight, style, file] of faces) {
    const path = join(fontsDir, pkg, 'files', file)
    const b64 = readFileSync(path).toString('base64')
    rules.push(
      `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  src: url(data:font/woff2;base64,${b64}) format('woff2');\n  font-display: swap;\n}`,
    )
  }
}

const css = rules.join('\n\n')
const ts = `/**
 * Generated by scripts/gen-shell-fonts.mjs — do not edit by hand.
 * Self-hosted Claude font faces (base64 data URIs) for the injected desktop
 * shell chrome. Rebuild with \`pnpm fonts\` after bumping @fontsource.
 */
export const SHELL_FONTS_CSS = ${JSON.stringify(css)}
`
writeFileSync(join(packageRoot, 'src', 'main', 'shell-fonts.css.ts'), ts)
console.log(`shell-fonts.css.ts written (${Math.round(css.length / 1024)} KiB of @font-face CSS)`)
